"""Generate Tables.java for the native Android app from core/repository.py and core/activity.py
(tenant-scoped tables and module keys stay identical to the website)."""
from pathlib import Path
import re, sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core.repository import TENANT_SCOPED_TABLES  # noqa: E402
act = (ROOT / "core/activity.py").read_text()
pairs = re.findall(r'^\s*"([a-z_0-9]+)":\s*"([A-Z_]+)",', act, re.M)
out = ["package com.fourstar.qcmsapp;", "", "import java.util.HashMap;", "import java.util.HashSet;", "import java.util.Map;", "import java.util.Set;", "",
       "/** GENERATED by scripts/gen_android_tables.py - do not edit. Same lists as core/repository.py + core/activity.py. */",
       "public final class Tables {", "    private Tables() { }", "    public static final Set<String> TENANT = new HashSet<>();",
       "    private static final Map<String, String> MODULE = new HashMap<>();", "    static {"]
for t in sorted(TENANT_SCOPED_TABLES):
    out.append(f'        TENANT.add("{t}");')
seen = set()
for t, m in pairs:
    if t in seen:
        continue
    seen.add(t)
    out.append(f'        MODULE.put("{t}", "{m}");')
out += ["    }", "", "    public static String moduleFor(String table) {", "        String m = MODULE.get(table);", '        return m == null ? "QCMS_APP" : m;', "    }", "}", ""]
dest = ROOT / "mobile/android_qcms_app/app/src/main/java/com/fourstar/qcmsapp/Tables.java"
dest.write_text("\n".join(out))
print(dest, len(TENANT_SCOPED_TABLES), len(seen))

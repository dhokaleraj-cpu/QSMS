def open_task(task: Mapping[str, Any]) -> None:
    import streamlit as st
    from core.repository import Repository
    pages = st.session_state.get("_qsms_pages") or {}
    table, related = str(task.get("related_table") or ""), str(task.get("related_id") or "")
    if table and related and table not in {"qcms_delete_requests", "npd_order_steps"}:
        try:
            rows = Repository().select(table, eq={"id": related}, limit=1)
        except Exception:
            rows = []

# --------------------------------------------------------------------------------------------- Python engine
def _as_date(value: Any) -> date | None:
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    text = str(value).strip()
    try:
        return date.fromisoformat(text[:10])
    except ValueError:
        return None


def _month_start(today: date, months: int) -> date:
    index = today.year * 12 + (today.month - 1) + int(months)
    return date(index // 12, index % 12 + 1, 1)


def _relative(value: Any, today: date) -> date | None:
    if isinstance(value, Mapping):
        if "today" in value:
            from datetime import timedelta
            return today + timedelta(days=int(value["today"]))
        if "month_start" in value:
            return _month_start(today, int(value["month_start"]))
    return None


def _get(row: Mapping[str, Any], col: Any) -> Any:
    if isinstance(col, (list, tuple)):
        for name in col:
            value = _get(row, name)
            if value is not None:
                return value
        return None
    name = str(col)
    if "." in name:
        head, key = name.split(".", 1)
        blob = row.get(head)
        if isinstance(blob, str):
            try:
                blob = json.loads(blob)
            except ValueError:
                blob = None
        if isinstance(blob, Mapping):
            inner = blob.get(key)
            return None if inner is None else (json.dumps(inner) if isinstance(inner, (dict, list)) else inner)
        return None
    return row.get(name)


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def _num(value: Any) -> float | None:
    if value is None or value == "" or isinstance(value, bool):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _truthy(value: Any) -> bool:
    return value is True or _text(value).strip().casefold() in {"true", "t", "1", "yes"}


def _compare(op: str, left: Any, right: Any) -> bool:
    if left is None or right is None:
        return False
    return {"eq": left == right, "lt": left < right, "lte": left <= right, "gt": left > right, "gte": left >= right,
            "neq": left != right}.get(op, False)


def matches(row: Mapping[str, Any], cond: Any, *, today: date | None = None,
            related: Mapping[str, Sequence[Mapping[str, Any]]] | None = None) -> bool:
    """Evaluate a filter (list = AND) on one row - identical semantics to SQL ``qcms_kpi_where``."""
    today = today or date.today()
    if cond is None:
        return True
    if isinstance(cond, (list, tuple)):
        return all(matches(row, c, today=today, related=related) for c in cond)
    if "any" in cond:
        return any(matches(row, c, today=today, related=related) for c in cond["any"])
    if "all" in cond:
        return matches(row, cond["all"], today=today, related=related)
    if "not" in cond:
        return not matches(row, cond["not"], today=today, related=related)
    for kind in ("exists", "not_exists"):
        if kind in cond:
            spec = cond[kind]
            children = (related or {}).get(spec["table"]) or []
            found = any(str(child.get(spec["fk"]) or "") == str(row.get("id") or "") and matches(child, spec.get("where") or [], today=today, related=related)
                        for child in children)
            return found if kind == "exists" else not found
    op = str(cond.get("op") or "eq")
    value = cond.get("value")
    raw = _get(row, cond.get("col"))
    if op == "blank":
        return _text(raw).strip() == ""
    if op == "not_blank":
        return _text(raw).strip() != ""
    if op == "true":
        return _truthy(raw)
    if op == "not_true":
        return not _truthy(raw)
    rel = _relative(value, today)
    if rel is not None:
        return _compare(op, _as_date(raw), rel)
    if op == "in":
        return raw is not None and _text(raw) in {str(v) for v in value or []}
    if op == "not_in":
        return _text(raw) not in {str(v) for v in value or []}
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return _compare(op, _num(raw), float(value))
    if op == "eq":
        return raw is not None and _text(raw) == str(value)
    if op == "neq":
        return _text(raw) != str(value)
    return _compare(op, None if raw is None else _text(raw), str(value))


def _tone(metric: Metric, value: float) -> str:
    if metric.tone == "alert":
        return "critical" if value > 0 else "good"
    if metric.tone == "watch":
        return "warning" if value > 0 else "good"
    if metric.tone == "done":
        return "good"
    if metric.tone == "rate":
        return "critical" if value > 5 else ("warning" if value > 0 else "good")
    return "neutral"


def metric_rows(key: str, rows: Iterable[Mapping[str, Any]], *, today: date | None = None,
                related: Mapping[str, Sequence[Mapping[str, Any]]] | None = None) -> list[Mapping[str, Any]]:
    group, metric = METRICS_BY_KEY[key]
    flt = list(group.base) + list(metric.filter)
    return [r for r in rows if matches(r, flt, today=today, related=related)]


def metric_value(key: str, rows: Sequence[Mapping[str, Any]], *, today: date | None = None,
                 related: Mapping[str, Sequence[Mapping[str, Any]]] | None = None) -> tuple[float, int]:
    """(card value, drill row count). For ``count`` both are equal; for ``percent`` value = num / den * 100."""
    group, metric = METRICS_BY_KEY[key]
    hits = len(metric_rows(key, rows, today=today, related=related))
    if metric.measure == "percent":
        den = sum(1 for r in rows if matches(r, list(group.base) + list(metric.den_filter), today=today, related=related))
        return (round(100.0 * hits / den, 1) if den else 0.0), hits
    return float(hits), hits


def _spark(group: ModuleGroup, rows: Sequence[Mapping[str, Any]], today: date, related: Mapping | None) -> list[int]:
    scoped = [r for r in rows if matches(r, list(group.base), today=today, related=related)]
    out = []
    for back in range(-5, 1):
        start, end = _month_start(today, back), _month_start(today, back + 1)
        out.append(sum(1 for r in scoped if (d := _as_date(r.get(group.spark))) is not None and start <= d < end))
    return out


def card_payload(group: ModuleGroup, metric: Metric, value: float, count: int) -> dict:
    return {"key": metric.key, "label": metric.label, "value": value, "unit": metric.unit, "tone": _tone(metric, value),
            "route": group.route, "count": count, "drill": drill_spec(metric.key)}


def groups_for(department: str | None = None, modules: Sequence[str] | None = None, home: str | None = None) -> list[ModuleGroup]:
    out = []
    for g in MODULE_GROUPS:
        if department and g.department != str(department).upper():
            continue
        if modules and g.key not in set(modules):
            continue
        if home and home not in g.homes:
            continue
        out.append(g)
    return out


def compute_groups(rows_by_table: Mapping[str, Sequence[Mapping[str, Any]]], *, department: str | None = None,
                   modules: Sequence[str] | None = None, today: date | None = None) -> list[dict]:
    """Python engine: same JSON as ``qcms_module_kpis()->'groups'`` from rows already loaded per table."""
    today = today or date.today()
    out = []
    for group in groups_for(department, modules):
        if group.table not in rows_by_table:
            continue
        rows = list(rows_by_table.get(group.table) or [])
        cards = []
        for metric in group.metrics:
            value, count = metric_value(metric.key, rows, today=today, related=rows_by_table)
            cards.append(card_payload(group, metric, value, count))
        payload = group_definition(group)
        payload.pop("base", None)
        payload.update({"cards": cards, "spark": _spark(group, rows, today, rows_by_table)})
        out.append(payload)
    return out


def drill_rows(key: str, rows: Sequence[Mapping[str, Any]], *, today: date | None = None,
               related: Mapping[str, Sequence[Mapping[str, Any]]] | None = None,
               labels: Mapping[str, Mapping[str, str]] | None = None, limit: int = 500) -> list[dict]:
    """Python engine: same rows (shape + order) as SQL ``qcms_kpi_drilldown`` for a module metric key."""
    group, _metric = METRICS_BY_KEY[key]
    labels = labels or {}
    parts, parties = labels.get("parts") or {}, labels.get("parties") or {}
    hits = list(metric_rows(key, rows, today=today, related=related))
    hits.sort(key=lambda r: (_as_date(r.get(group.date)) or date.min, str(r.get("created_at") or "")), reverse=True)
    out = []
    for r in hits[: max(1, int(limit))]:
        ref = next((_text(r.get(c)) for c in group.ref if _text(r.get(c)).strip()), "") or _text(r.get("id"))[:8]
        party_id = next((_text(r.get(c)) for c in group.party if r.get(c)), "")
        detail = " · ".join(f"{p} {_text(r.get(c))}".strip() for p, c in group.detail if _text(r.get(c)).strip())
        day = _as_date(r.get(group.date))
        out.append({"source_table": group.table, "record_id": _text(r.get("id")), "reference": ref,
                    "part": parts.get(_text(r.get(group.part)), "") if group.part else "", "party": parties.get(party_id, "") if party_id else "",
                    "status": _text(r.get(group.status)) if group.status else "", "record_date": day.isoformat() if day else "", "detail": detail})
    return out


def related_tables(groups: Iterable[ModuleGroup]) -> set[str]:
    """Child tables referenced by exists / not_exists filters."""
    found: set[str] = set()

    def walk(node: Any) -> None:
        if isinstance(node, (list, tuple)):
            for n in node:
                walk(n)
        elif isinstance(node, Mapping):
            for kind in ("exists", "not_exists"):
                if kind in node:
                    found.add(str(node[kind]["table"]))
                    walk(node[kind].get("where"))
            for k in ("any", "all", "not"):
                if k in node:
                    walk(node[k])

    for g in groups:
        walk(list(g.base))
        for m in g.metrics:
            walk(list(m.filter))
            walk(list(m.den_filter))
    return found



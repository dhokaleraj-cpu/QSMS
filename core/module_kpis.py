def render_modules_view(repo: Any, profile: Mapping[str, Any] | None, *, key: str = "kpi_modules_view") -> None:
    """KPI dashboard "Modules" view: one tab per department, every module group with its KPI cards + my tasks."""
    import streamlit as st
    labels = [label for _code, label in DEPARTMENTS]
    tabs = st.tabs(labels)
    all_tasks = _cached_tasks(_user_key(profile), repo)
    for (code, label), tab in zip(DEPARTMENTS, tabs):
        with tab:
            wanted = tuple(g.key for g in groups_for(code))
            groups = _permitted(_cached_groups(_user_key(profile), wanted, repo), profile)
            if not groups:
                st.caption(f"No {label} modules available for your access.")

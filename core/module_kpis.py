def load_groups(repo: Any, *, department: str | None = None, modules: Sequence[str] | None = None,
                rpc_only: bool = False) -> list[dict]:
    """Module KPI groups: SQL engine (``qcms_module_kpis``) first, Python engine on the same filters as fallback."""
    try:
        data = repo.rpc(KPI_RPC, {"p_department": department, "p_modules": list(modules) if modules else None})
        if isinstance(data, list):
            data = data[0] if data else {}
        groups = (data or {}).get("groups") if isinstance(data, Mapping) else None
        if isinstance(groups, list):
            return [dict(g) for g in groups if isinstance(g, Mapping)]
    except Exception:
        if rpc_only:
            return []
    selected = groups_for(department, modules)
    tables = {g.table for g in selected} | related_tables(selected)
    rows_by_table: dict[str, list[dict]] = {}
    for table in sorted(tables):
        try:
            rows_by_table[table] = list(repo.select(table, limit=5000) or [])
        except Exception:
            continue
    return compute_groups(rows_by_table, department=department, modules=modules)


def load_drill(repo: Any, key: str, *, limit: int = 500) -> list[dict] | None:
    """Rows behind a card: ``qcms_kpi_drilldown`` → ``qcms_kpi_records`` (older DB) → Python engine. None = unavailable."""
    key = str(key or "")
    for name, params in ((DRILL_RPC, {"p_card_key": key, "p_limit": limit}),
                         ("qcms_kpi_records", {"p_card_key": key, "p_department": None, "p_limit": limit})):
        try:
            data = repo.rpc(name, params)
        except Exception:
            continue
        if isinstance(data, Mapping):
            data = [data]
        rows = [dict(r) for r in (data or []) if isinstance(r, Mapping)]
        if rows and not all("record_id" in r and "source_table" in r for r in rows):
            continue  # not the drill-down row shape (unexpected payload) - try the next source
        return rows
    if key not in METRICS_BY_KEY:
        return None
    group, _metric = METRICS_BY_KEY[key]
    try:
        rows = list(repo.select(group.table, limit=5000) or [])
        related = {t: list(repo.select(t, limit=5000) or []) for t in related_tables([group])}
    except Exception:
        return None
    labels: dict[str, dict[str, str]] = {"parts": {}, "parties": {}}
    try:
        labels["parts"] = {str(p.get("id")): " · ".join(x for x in (str(p.get("part_number") or ""), str(p.get("part_name") or "")) if x)
                           for p in repo.select("parts", limit=5000)}
        labels["parties"] = {str(p.get("id")): str(p.get("party_name") or p.get("party_code") or "") for p in repo.select("parties", limit=5000)}
    except Exception:
        pass
    return drill_rows(key, rows, related=related, labels=labels, limit=limit)



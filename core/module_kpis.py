def render_module_strip(*, home: str = "", modules: Sequence[str] | None = None, department: str | None = None, key: str,
                        origin: str = "", show_tasks: bool = True) -> None:
    """Module home pages: infographic KPI rows at the top + my pending tasks of these modules. Never raises."""
    import streamlit as st
    try:
        from core.auth import current_profile
        from core.repository import Repository
        profile = current_profile() or {}
        wanted = [g.key for g in groups_for(department, modules, home or None)]
        if not wanted:
            return
        groups = _cached_groups(_user_key(profile), tuple(wanted), Repository())
        groups = _permitted(groups, profile)
        if not groups:
            return
        all_tasks = _cached_tasks(_user_key(profile), Repository()) if show_tasks else []
        with st.container(border=True, key=f"qcms_module_strip_{key}"):
            def one(group: Mapping[str, Any]) -> None:
                g = GROUPS_BY_KEY.get(str(group.get("key")))
                render_group(group, key=key, origin=origin, tasks=tasks_for_group(g, all_tasks) if g else [])

            if len(groups) > 3:  # many modules (e.g. Supply Chain home): one tab per module keeps the page short
                def tab_label(group: Mapping[str, Any]) -> str:
                    alerts = sum(1 for c in group.get("cards") or [] if c.get("tone") in {"critical", "warning"} and float(c.get("value") or 0) > 0)
                    return f"{group.get('icon') or ''} {group.get('title')}" + (f" · {alerts}⚠" if alerts else "")
                for tab, group in zip(st.tabs([tab_label(g) for g in groups]), groups):
                    with tab:
                        one(group)
            else:
                for group in groups:
                    one(group)
            mine = [t for group in groups if (g := GROUPS_BY_KEY.get(str(group.get("key")))) for t in tasks_for_group(g, all_tasks)]
            if mine:
                render_task_list(mine, key=f"{key}_tasks")
    except Exception as exc:  # noqa: BLE001 - the module page must still open
        st.caption(f"Module KPIs are not available right now ({str(exc)[:120]}).")



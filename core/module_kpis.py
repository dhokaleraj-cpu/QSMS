def C(col: str | Sequence[str], op: str, value: Any = None) -> dict:
    out: dict[str, Any] = {"col": list(col) if isinstance(col, (list, tuple)) else col, "op": op}
    if value is not None:
        out["value"] = list(value) if isinstance(value, tuple) else value
    return out


def ANY(*conds: dict) -> dict:
    return {"any": list(conds)}


def NOT(cond: dict) -> dict:
    return {"not": cond}


def TODAY(days: int = 0) -> dict:
    return {"today": int(days)}


def MONTH(months: int = 0) -> dict:
    return {"month_start": int(months)}


@dataclass(frozen=True)
class Metric:
    key: str
    label: str
    filter: tuple[dict, ...] = ()
    tone: str = "watch"              # watch (amber if > 0) | alert (red if > 0) | done (green) | info (neutral) | rate (%)
    unit: str = ""
    measure: str = "count"           # count | percent (numerator = filter, denominator = den_filter)
    den_filter: tuple[dict, ...] = ()


@dataclass(frozen=True)
class ModuleGroup:
    key: str
    title: str
    department: str
    icon: str
    route: str                        # module page / register (web route)
    module_key: str                   # permission module (core.access)
    table: str
    metrics: tuple[Metric, ...]
    base: tuple[dict, ...] = ()       # scope of the module (applies to every metric)
    ref: tuple[str, ...] = ("id",)    # reference columns (first non-blank)
    date: str = "created_at"          # record date (drill grid + sort)
    part: str = ""                    # part id column ("" = none)
    party: tuple[str, ...] = ()       # customer / supplier id columns (first non-null)
    status: str = "status"            # "" = table without a status column
    detail: tuple[tuple[str, str], ...] = ()   # (prefix, column)
    spark: str = "created_at"         # 6-month trend column
    task_routes: tuple[str, ...] = ()
    homes: tuple[str, ...] = ()       # module home pages that show this group
    entry_route: str = ""             # "+ new" route



def tasks_for_group(group: ModuleGroup, tasks: Iterable[Mapping[str, Any]]) -> list[dict]:
    """My pending tasks (qcms_my_pending_tasks) that belong to this module."""
    out = []
    for task in tasks or []:
        table = str(task.get("related_table") or "")
        route = str(task.get("web_route") or "")
        if table == group.table or (route and (route in group.task_routes or route == group.route)):
            if group.base and table == group.table and group.key in {"metlab", "bend"}:
                is_bend = route == "bend-test-entry"
                if (group.key == "bend") != is_bend:
                    continue
            out.append(dict(task))
    return out



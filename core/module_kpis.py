def _fmt(value: Any, unit: str = "") -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value or "0")
    if unit == "%":
        return f"{number:,.1f}%"
    return f"{number:,.0f}" if abs(number - round(number)) < 1e-9 else f"{number:,.2f}"


def sparkline_svg(values: Sequence[Any], color: str = "#0B6E70", width: int = 96, height: int = 24) -> str:
    numbers = []
    for v in values or []:
        try:
            numbers.append(float(v))
        except (TypeError, ValueError):
            numbers.append(0.0)
    if len(numbers) < 2:
        return ""
    top = max(numbers) or 1.0
    step = width / (len(numbers) - 1)
    points = " ".join(f"{i * step:.1f},{height - 2 - (n / top) * (height - 4):.1f}" for i, n in enumerate(numbers))
    return (f'<svg viewBox="0 0 {width} {height}" width="{width}" height="{height}" aria-label="6-month trend">'
            f'<polyline fill="none" stroke="{color}" stroke-width="2" stroke-linejoin="round" stroke-linecap="round" points="{points}"/></svg>')



"""QCMS R37 · module infographic KPIs with drill-down (one definition, two engines that always agree).

Every module (MetLAB, Dimensional, Bend Test, RMTC, Material Inward, OSP, complaints, calibration, standard
room, QC calculations, customer orders, POs, RM, forging, dispatch, opening stock, NPD / APQP, masters,
indirect purchase) has 3-6 KPI cards. Each card is a *count of rows of one table that match a JSON filter*
(or a percentage of two such counts). The same JSON filter produces

* the number on the card            - SQL ``public.qcms_module_kpis`` (security invoker, RLS) or ``compute_groups``
* the list behind the number        - SQL ``public.qcms_kpi_drilldown`` or ``drill_rows``

so the count on a card and the number of rows in its drill-down are identical by construction. The SQL
engine reads the definitions from ``public.qcms_kpi_definitions()``, which the R37 migration embeds as a JSON
literal generated by :func:`definitions_json` (a test keeps both in sync).

Filter language (JSON, list = AND)::

    {"col": "status", "op": "eq|neq|in|not_in|lt|lte|gt|gte|blank|not_blank|true|not_true", "value": ...}
    {"any": [ ... ]}   OR          {"not": {...}}   negation
    {"not_exists": {"table": "inspection_plans", "fk": "part_id", "where": [...]}}  (also "exists")

``col`` may be a list (``coalesce`` of the columns) or ``"results.inspection_method"`` (jsonb ->> key).
``value`` may be ``{"today": n}`` (current date + n days) or ``{"month_start": n}`` (first day of this
month + n months); the column is then compared as a date. Text comparisons are null-safe (null = '').
Every condition is two-valued (null -> false), in SQL and in Python.
"""
